/** 图片生成的结构约束；用户要求决定构图、视角和主体数量。 */
const quality = '画面质量约束：保持主体真实、结构合理、部件完整、比例和透视一致；同一商品在各视角保持相同外形、颜色、材质和已有标识。避免畸形、扭曲、融合、悬浮、重复或缺失部件、异常连接、穿插和不可能的几何结构；人物出现时保持自然解剖和正确肢体数量。不得为填充画面添加未要求的物体、文字或装饰。多视角要求应呈现同一物品的不同观察角度，清晰分区、互不重叠，不要只复制同一个角度。'
const white = '白底要求：以参考原图中的真实商品为唯一依据，只编辑背景，不重新设计或重绘商品。商品可见细节保真优先于美化和排版。保留商品轮廓、比例、颜色与材质，以及原有纹理、透明度、反光和细小结构，不简化、磨平、替换或美化。保留商品本体上的文字与标识（例如键帽字符、瓶身标签或包装印刷），不修改包装文字、图案、按钮及接口，包括字形、内容、位置、数量和连接关系；看不清或被遮挡的细节不得猜测、补写或重构。不增加原图中不存在的配件，不删除属于商品的零部件。\n\n移除原背景、无关物体和人物，使用纯白背景（#FFFFFF），保留自然接触阴影及与原图一致的光照关系，不添加场景、道具、镜面倒影或装饰。删除原图中商品之外的所有文字，包括宣传标题、卖点、字幕、角标、水印、悬浮Logo及平台标识，不把包装上的真实文字误作背景文字删除。\n\n默认保留原图视角、朝向、商品数量及可见结构，仅等比缩放并调整留白，不拉伸、不裁断商品，不擅自改成正面或生成新角度。用户明确要求的视角、数量和排版优先于默认单视角；要求多视角时，在同一张画布内排列正面、侧面、四分之三视角，或用户指定的角度，各视角留边、比例一致，并以所提供的参考视角为依据，不得以多视角要求为由改变商品结构或编造未见细节。只输出一张图片指一个输出文件，不限制其中的视角数量。'

/**
 * 组合用户要求及通用质量约束，保持用户要求原文。
 * @param {string} prompt 用户填写的提示词。
 * @returns {string} 发送给图片供应商的完整提示词。
 */
export function imagePrompt(prompt) {
  return `用户本次生成要求：\n${prompt}\n\n${quality}`
}

/**
 * 白底编辑优先保留原图商品细节及视角；仅显式多视角要求可改变默认排版。
 * @param {string} prompt 用户填写的生成要求，可为空。
 * @returns {string} 发送给白底图供应商的完整提示词。
 */
export function whiteBackgroundPrompt(prompt) {
  return `${imagePrompt(prompt.trim() || '只替换原背景，保留原图商品细节和视角，制作纯白底商品图。')}\n\n${white}`
}
