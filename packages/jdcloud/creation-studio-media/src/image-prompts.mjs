/** 图片生成的结构约束；用户要求决定构图、视角和主体数量。 */
const quality = '画面质量约束：保持主体真实、结构合理、部件完整、比例和透视一致；同一商品在各视角保持相同外形、颜色、材质和已有标识。避免畸形、扭曲、融合、悬浮、重复或缺失部件、异常连接、穿插和不可能的几何结构；人物出现时保持自然解剖和正确肢体数量。不得为填充画面添加未要求的物体、文字或装饰。多视角要求应呈现同一物品的不同观察角度，清晰分区、互不重叠，不要只复制同一个角度。'
const white = '白底要求：从参考图识别用户指定商品，移除原背景、无关物品和人物，使用纯白背景。保留商品本体上的文字与标识（例如键帽字符、瓶身标签或包装印刷）；删除原图中商品之外的所有文字，包括宣传标题、卖点、字幕、角标、水印、悬浮Logo及平台标识。用户明确要求的视角、数量和排版优先于默认居中单视角；要求多视角时，在同一张画布内排列正面、侧面、四分之三视角，或用户指定的角度，各视角完整留边、比例一致。只输出一张图片指一个输出文件，不限制其中的视角数量。没有自定义要求时，生成完整居中的单视角纯白底商品图。'

/**
 * 组合用户要求及通用质量约束，保持用户要求原文。
 * @param {string} prompt 用户填写的提示词。
 * @returns {string} 发送给图片供应商的完整提示词。
 */
export function imagePrompt(prompt) {
  return `用户本次生成要求：\n${prompt}\n\n${quality}`
}

/**
 * 组合白底生成规则；单张文件可包含用户要求的多个视角。
 * @param {string} prompt 用户填写的生成要求，可为空。
 * @returns {string} 发送给白底图供应商的完整提示词。
 */
export function whiteBackgroundPrompt(prompt) {
  return `${imagePrompt(prompt.trim() || '制作纯白底商品图。')}\n\n${white}`
}
